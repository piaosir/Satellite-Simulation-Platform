// 别名（同一支画笔画多个 symbol id）
const ALIAS = { 'dish-small': 'dish', mast: 'tower', nvr: 'server' }

export const symbolIds = () => Object.keys(SYMBOLS)
export const hasSymbol = (id) => !!(SYMBOLS[id] || SYMBOLS[ALIAS[id]])

/**
 * 2D / 拓扑图：把符号画在 (x, y)，边长 size。
 * color 是主色（实心件），套色描边固定用 SYM_CASE；k:true 的件用套色画（做「洞」）。
 * rot 弧度，缺省 0（本套符号一律正立，只有载具类会被调用方转向）。
 */
export function drawSymbol(ctx, id, x, y, size, color, rot, caseColor) {
  const parts = SYMBOLS[id] || SYMBOLS[ALIAS[id]] || SYMBOLS.sensor
  const s = size / SYM_VB
  const kc = caseColor || SYM_CASE
  ctx.save()
  ctx.translate(x, y)
  if (rot) ctx.rotate(rot)
  ctx.scale(s, s)
  ctx.translate(-SYM_VB / 2, -SYM_VB / 2)
  ctx.lineJoin = 'round'; ctx.lineCap = 'round'
  for (const p of parts) {
    tracePrim(ctx, p.d)
    ctx.globalAlpha = p.o == null ? 1 : p.o
    if (p.s === 'fill') { ctx.fillStyle = p.k ? kc : (color || '#fff'); ctx.fill() }
    else { ctx.strokeStyle = p.k ? kc : (color || '#fff'); ctx.lineWidth = p.w || 7; ctx.stroke() }
  }
  ctx.globalAlpha = 1
  ctx.restore()
}

/**
 * 3D：现画一张 size×size 的 canvas 供 CanvasTexture 用。
 * ★ 同步返回，绝不走「SVG → Image」那条异步路 —— 出图只渲有限几帧，异步贴图会整个不出现。
 */
export function symbolCanvas(id, px, color, caseColor) {
  const n = Math.max(16, Math.round(px || 64))
  const cv = document.createElement('canvas')
  cv.width = n; cv.height = n
  const ctx = cv.getContext('2d')
  // 套色底：3D 上没有地图底色兜着，先铺一层半透明深色让符号在亮底上也立得住
  drawSymbol(ctx, id, n / 2, n / 2, n * 0.92, color, 0, caseColor)
  return cv
}

export default { drawSymbol, symbolCanvas, symbolIds, hasSymbol, SYM_VB, SYM_CASE }
