export const STATION_VB = 128         // 符号画布边长（正方形；两处绘制都按 si×si 铺）
export const STATION_CASE = 'rgba(6,11,18,0.82)'
const CASE_W = 4.4                    // 套色描边宽（128 视框下）≈ 28px 档的 0.96 px、40px 档的 1.4 px

// ★ 坐标锚点 = 底盘几何中心。2D 按 (x − si·ANCHOR_X, y − si·ANCHOR_Y) 落笔，
//   3D 按 sprite.center.set(ANCHOR_X, 1 − ANCHOR_Y)。四个数必须一起改，否则 2D 与 3D 的站址会错开。
export const STATION_ANCHOR_X = 57.06 / STATION_VB
export const STATION_ANCHOR_Y = 112.85 / STATION_VB

// 第一趟：整体垫一层深色剪影。两类图元分开处理 ——
//   实心块（有 fill）：填 casing 色再粗描一圈，向外胀出 CASE_W/2
//   描边线（fill="none"，如馈源杆）：不能填，只能把自己的 stroke-width 加粗
function casingPass() {
  return NOTO_BODY
    .replace(/<path fill="none"[^>]*stroke-width="([\d.]+)"([^>]*)\/>/g,
      (m, sw, rest) => `<path fill="none" stroke="${STATION_CASE}" stroke-linecap="round" stroke-width="${(+sw + CASE_W).toFixed(1)}"${rest}/>`)
    // ★ fill 不一定紧跟标签名：两个 <ellipse> 的 fill 排在 cx/cy 之后。按「紧跟标签」写正则会漏掉它们，
    //   垫底层就在碟面那块白椭圆的位置留一个白洞，边缘露白边而不是深边。
    .replace(/<(path|ellipse)([^>]*?)\sfill="(?!none)[^"]*"/g,
      `<$1$2 fill="${STATION_CASE}" stroke="${STATION_CASE}" stroke-width="${CASE_W}" stroke-linejoin="round"`)
    .replace(/opacity="[\d.]+"/g, '')   // 垫底层不透明，否则边缘会露出半透的灰圈
}

// 生成符号 SVG。这枚图形是 Noto 的固定六色配色，不着色也不换形状 —— 它是地球站这一层唯一的符号。
// 深色套边（casingPass）保证浅底图上也切得出轮廓。
export function stationSvg() {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${STATION_VB} ${STATION_VB}">`
    + casingPass() + NOTO_BODY + '</svg>'
}
