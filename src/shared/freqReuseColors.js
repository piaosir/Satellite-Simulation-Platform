// 频率复用配色板（波束合成的频率配色 F# ↔ 频率计划的波束色，两处共用这一份）。
//
// 一个色号在这套软件里贯穿两个模块：波束合成负责【几何】（哪个波束在哪、谁与谁同色），
// 频率计划负责【频率】（这一色占哪一段、多宽）。两边画的必须是同一个色 —— 各存一份迟早漂开，
// 故 palette 提到这里，两处 import 同一个。
//
// 饱和度压过、地图上不刺眼。前 8 个是 8 个色相（三/四/七色取前 3/4/7 个），后 8 个是同色相压深
// 的一档 —— ★ F(i) 与 F(i+8) 同色相：十六色在工程上就是【8 频段 × 2 极化】（中星26 小波束那族
// 正是：色1..8 与色9..16 两两同频段、极化正交），同色相分深浅正好读成「同一段频率的两个极化」。
// 16 个各不相同的色相反而谁也认不出谁。
// 分配算法只认下标、不认色相配对；色相 ↦ 频段/极化的映射是频率计划模块那一层的事。
export const FC_PALETTE = [
  0xe05252, 0xf2c14e, 0x3fb77f, 0x4f8fe8, 0xa06fdc, 0xf08a3c, 0x38b8b0, 0xd76a9e,
  0xa83b3b, 0xc08a12, 0x1f8a5c, 0x2f5fb0, 0x6f45ac, 0xc25f14, 0x1c8a84, 0xa3396b
]
// 下标取模回绕（负数亦可）：色数可以超过 16，颜色从头再来一轮
export const fcHex = (i) => FC_PALETTE[((i % FC_PALETTE.length) + FC_PALETTE.length) % FC_PALETTE.length]
export const fcCss = (i) => '#' + fcHex(i).toString(16).padStart(6, '0')
