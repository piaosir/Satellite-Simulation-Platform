function poly(c, x) {
  let s = 0;
  for (let i = c.length - 1; i >= 0; i--) s = s * x + c[i];
  return s;
}

/**
 * 标准正态分布的逆累积函数 F⁻¹(P)：返回 x 使 Φ(x) = P。
 * P ∈ (0,1)；P = 0 / 1 返回 ∓Infinity，越界返回 NaN。
 */
function invNormal(p) {
  if (!(p > 0 && p < 1)) return p === 0 ? -Infinity : (p === 1 ? Infinity : NaN);
  const q = p - 0.5;
  if (Math.abs(q) <= 0.425) {
    const r = 0.180625 - q * q;
    return q * poly(A, r) / poly(B, r);
  }
  let r = Math.sqrt(-Math.log(q < 0 ? p : 1 - p));
  let v;
  if (r <= 5) { r -= 1.6; v = poly(C, r) / poly(D, r); } else { r -= 5; v = poly(E, r) / poly(F, r); }
  return q < 0 ? -v : v;
}

/** 逆互补正态函数 Q⁻¹(x)：返回 y 使 Q(y) = 1 − Φ(y) = x。即 Q⁻¹(x) = −F⁻¹(x)。 */
function qInv(x) {
  return -invNormal(x);
}

