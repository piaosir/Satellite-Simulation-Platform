const LOG10 = Math.log10;

/**
 * 单刀刃绕射损耗近似 J(ν)（dB）。
 * P.452-18 式 (13)：J(ν) = 6.9 + 20lg(√((ν−0.1)²+1) + ν − 0.1)，J(−0.78) ≈ 0 为下界，ν ≤ −0.78 时取 0。
 * P.2108-1 式 (1) 同式（「J(ν) is set to zero for ν ≤ −0.78」）。
 */
function knifeEdgeJ(nu) {
  if (!(nu > -0.78)) return 0;
  const t = nu - 0.1;
  return 6.9 + 20 * LOG10(Math.sqrt(t * t + 1) + t);
}

