'use strict'
// PFD Mask 生成（ITU-R S.1503）：引擎 → XSD 校验 → 三种文件划分的 XML → 运行参数文件，放在 worker_threads 里跑。
//
// 为什么单开线程：默认 60×60×23 网格约 1.1 s、120 点 / 2° 一档约 14 s，全是同步长调用。从前在 ipcMain 里
// 直接算，期间主进程事件循环被整个占住——所有窗口的 IPC、菜单、窗口拖动一起卡死。照 occtWorker.js 的先例
// 按磁盘路径起 worker（electron/** 整个进 asar，dev 与打包后是同一条相对路径），一次计算一个，算完即退。
//
// 本文件三个角色：
//   generate(req, hooks)  纯计算（不碰 electron），worker 里跑；回归测试直接调它，与 worker 走同一份代码
//   start(req, opts)      主进程侧：起 worker、转进度、可取消，返回 { promise, cancel }
//   worker 入口           以 worker 身份载入（workerData.kind === WORKER_KIND）时执行
//
// 消息：主 → workerData { kind, req, cancel: SharedArrayBuffer(4) }
//       回 → { type:'progress', done, total } … { type:'done', result } | { type:'canceled' } | { type:'error', message }
// 结果里的 XML 在 worker 里就转成 UTF-8 字节、转移所有权回主进程（不拷贝）：XML 头注释带中文，字符串在 V8 里
// 是双字节，32 MB 的掩模按字符串搬要占 64 MB、三种划分再乘三；字节既省一半，落盘时也原样写。
const { Worker, isMainThread, parentPort, workerData } = require('worker_threads')

const WORKER_KIND = 'pfd-mask'
// 出 XML（一次校验 + 三种划分各拼一遍，每遍内部还要再校验）的工作量约为网格计算的 30%：
// 实测 60 点 / 5°（1.1 s 网格）与 120 点 / 2°（10.8 s 网格）两档都在 25–30%。只用来分配进度条的刻度
const XML_SHARE = 0.3

const canceledError = () => { const e = new Error('已取消'); e.canceled = true; return e }

/** 一份 job 的计算量（进度刻度用）：下行 pfd_mask 按网格格数计；星间 / 上行是一维表，一张约百来个角度点，与网格比可略。 */
function jobWeight(j) {
  try {
    const eng = require('../../packages/core/utils/pfdmask/maskEngine.js')
    const geo = require('../../packages/core/utils/pfdmask/alphaGeometry.js')
    const step = Number(j.latStepDeg) > 0 ? Number(j.latStepDeg) : 5
    const lat = eng.buildLatAxis(geo.latMaxFromInclination(j.incDeg), step).length
    const n = Math.round(Number(j.nAzElPoints) > 0 ? Number(j.nAzElPoints) : 60)
    const down = j.directions ? !!j.directions.down : true      // 旧单 job 形态缺 directions 时引擎缺省出下行
    return down ? lat * n * n : lat * 100
  } catch (e) { return 1 }
}

/**
 * 参数 → 掩模文档 → XSD 校验 → 三种文件划分（single / per-kind / per-mask）+ 运行参数文件。
 * 入参两种形态都收：
 *   单 job（旧）：直接是一份 params
 *   多 job（掩模表）：{ satName, ntcId, specVersion, jobs: [params, ...], operatingParams? } → 合并成一份文档
 * hooks：{ onProgress(done, total), shouldCancel() } —— 下行网格逐纬度切片回报 / 检查一次（引擎自带的两个钩子）。
 * 取消时抛 canceled=true 的错；其余失败按 { ok:false, error, … } 返回（形状与搬进 worker 之前的 pfd:generate 一致）。
 */
function generate(req, hooks) {
  const H = hooks || {}
  const eng = require('../../packages/core/utils/pfdmask/maskEngine.js')
  const io = require('../../packages/core/utils/pfdmask/maskIO.js')
  const t0 = Date.now()
  const jobs = Array.isArray(req && req.jobs) ? req.jobs : [req]
  const stopped = () => !!(H.shouldCancel && H.shouldCancel())

  const weights = jobs.map(jobWeight)
  const computeTotal = weights.reduce((a, w) => a + w, 0) || 1
  const total = computeTotal * (1 + XML_SHARE)
  const report = (done) => { if (H.onProgress) H.onProgress(Math.min(total, done), total) }
  const xmlStep = (frac) => report(computeTotal * (1 + XML_SHARE * frac))

  const doc = {
    ntcId: Number(req && req.ntcId !== undefined ? req.ntcId : jobs[0].ntcId),
    satName: String((req && req.satName) || jobs[0].satName || '').slice(0, 20),
    pfdMasks: [], eirpMaskEs: [], eirpMaskSs: []
  }
  const metas = []
  const jobErrors = []
  const discretion = []

  let base = 0
  for (let k = 0; k < jobs.length; k++) {
    if (stopped()) throw canceledError()
    const j = jobs[k], w = weights[k]
    try {
      const r = eng.generateMasks(j, {
        shouldCancel: H.shouldCancel,
        onProgress: (d, t) => report(base + (t > 0 ? (w * d) / t : 0))
      })
      // 合并：mask_id 的跨类唯一性由下面的 validateMaskDoc 统一把关
      doc.pfdMasks.push(...r.doc.pfdMasks)
      doc.eirpMaskEs.push(...r.doc.eirpMaskEs)
      doc.eirpMaskSs.push(...r.doc.eirpMaskSs)
      metas.push(r.meta)
      jobErrors.push(null)
      for (const d of (r.meta.discretion || [])) {
        if (!discretion.some((x) => x.field === d.field && String(x.value) === String(d.value))) discretion.push(d)
      }
    } catch (e) {
      if (stopped()) throw canceledError()        // 引擎在切片边界抛的「已取消」不能记成这一份 job 失败、接着算下一份
      metas.push(null)
      jobErrors.push((e && e.message) || String(e))
    }
    base += w
    report(base)
  }

  const hard = jobErrors.filter(Boolean)
  if (!doc.pfdMasks.length && !doc.eirpMaskEs.length && !doc.eirpMaskSs.length) {
    return { ok: false, error: hard[0] || '没有生成任何 mask', jobErrors, metas }
  }

  if (stopped()) throw canceledError()
  const v = io.validateMaskDoc(doc)
  xmlStep(0.1)
  if (!v.ok) {
    return {
      ok: false,
      error: `未通过 ITU 官方 XSD 校验，共 ${v.errors.length} 处`,
      errors: v.errors.slice(0, 20), jobErrors, metas
    }
  }
  const header = [
    'Generated by 卫星仿真平台 · PFD EIRP Mask Generator',
    'Schema: ITU masks schema v.4.0.0.0 (Rec. ITU-R S.1503-2)',
    `Modelled per ${(req && req.specVersion) || 'S.1503-4'}; exported against XSD v4.0.0.0`,
    'DISCRETIONARY SETTINGS (not specified by Rec. ITU-R S.1503):',
    ...discretion.map((d) => `  [${d.evidence}] ${d.field} = ${d.value} — ${d.why}`)
  ]
  // 三种切分粒度都出（各拼一遍字符串），渲染端改「文件划分」下拉即换列表、不必重算
  const files = {}
  const MODES = ['single', 'per-kind', 'per-mask']
  MODES.forEach((m, i) => {
    if (stopped()) throw canceledError()
    files[m] = io.buildMaskFiles(doc, { mode: m, header })
    xmlStep(0.1 + (0.9 * (i + 1)) / MODES.length)
  })
  const xml = files.single[0].xml

  // 第四份交付物：运行参数（规避角/终端密度/跟踪约束，都不进 mask XML）。
  // 按 S.1503-4 §B3.3 生成，旁挂独立文件——绝不塞进 mask 文件（Mask-schema.xsd 不含此元素）。
  const opFiles = []
  const opProblems = []
  if (req && req.operatingParams) {
    try {
      const opm = require('../../packages/core/utils/pfdmask/operatingParams.js')
      const chk = opm.validateOperatingParams(req.operatingParams)
      opProblems.push(...chk.errors, ...chk.warnings)
      if (chk.ok) {
        opFiles.push({
          filename: `Mask_param_id_${req.operatingParams.paramId}_OP.xml`,
          xml: opm.buildOperatingParamsXml(doc, req.operatingParams, {
            validate: false,
            header: [
              'Generated by 卫星仿真平台 · PFD EIRP Mask Generator',
              'Schema basis: Rec. ITU-R S.1503-4 §B3.3 (ITU has not published an XSD for this element)'
            ]
          })
        })
      }
    } catch (e) { opProblems.push((e && e.message) || String(e)) }
  }

  return {
    ok: true, xml, files, metas, jobErrors, discretion, opFiles, opProblems,
    counts: v.counts,
    warnings: v.warnings.slice(0, 20),
    elapsedMs: Date.now() - t0,
    bytes: Buffer.byteLength(xml, 'utf8')
  }
}

/**
 * worker 侧：把结果里每份文件的 XML 换成 UTF-8 字节（{ …, data: Uint8Array }，去掉 xml），返回转移清单。
 * TextEncoder 出的数组各自独占一块 ArrayBuffer（不是 Buffer 池里的切片），整块转移不会连带别人。
 */
function packBytes(r) {
  const transfer = []
  if (!r || !r.ok) return transfer
  const enc = new TextEncoder()
  const pack = (f) => { const data = enc.encode(f.xml); delete f.xml; f.data = data; transfer.push(data.buffer) }
  for (const m of Object.keys(r.files || {})) for (const f of r.files[m]) pack(f)
  for (const f of (r.opFiles || [])) pack(f)
  delete r.xml          // 就是 files.single[0] 那一份，不再多搬一遍
  return transfer
}

/** 主进程侧：回渲染端的形状——文件只留清单（文件名 / 类型 / 字节数），字节留在主进程等导出时取。 */
function slim(r) {
  const strip = (f) => ({ filename: f.filename, kind: f.kind, maskIds: f.maskIds, bytes: f.bytes })
  const files = {}
  for (const m of Object.keys(r.files || {})) files[m] = r.files[m].map(strip)
  const opFiles = (r.opFiles || []).map((f) => ({ filename: f.filename, bytes: f.data ? f.data.byteLength : 0 }))
  return Object.assign({}, r, { files, opFiles })
}

/**
 * 主进程侧：起一个 worker 跑 generate。返回 { promise, cancel }：
 *   promise  resolve = generate 的结果（文件带 data 字节）；取消时 reject 一个 canceled=true 的错
 *   cancel() 置取消标志（引擎在下一个纬度切片边界就停）并立即结束 worker——不等它自己退
 * opts.onProgress(done, total)：进度（worker 侧已节流到约 10 次/秒）。
 */
function start(req, opts) {
  const o = opts || {}
  const cancelBuf = new SharedArrayBuffer(4)
  let worker = null
  let settled = false
  let cancelFn = () => {}
  const promise = new Promise((resolve, reject) => {
    const finish = (fn, v) => {
      if (settled) return
      settled = true
      try { worker && worker.terminate() } catch (e) { /* 已退出 */ }
      fn(v)
    }
    try {
      worker = new Worker(__filename, { workerData: { kind: WORKER_KIND, req, cancel: cancelBuf } })
    } catch (e) { settled = true; reject(e); return }
    cancelFn = () => { Atomics.store(new Int32Array(cancelBuf), 0, 1); finish(reject, canceledError()) }
    worker.on('message', (m) => {
      if (!m || typeof m !== 'object') return
      if (m.type === 'progress') { try { if (o.onProgress) o.onProgress(m.done, m.total) } catch (e) { /* 进度回调出错不影响计算 */ } return }
      if (m.type === 'done') return finish(resolve, m.result)
      if (m.type === 'canceled') return finish(reject, canceledError())
      if (m.type === 'error') return finish(reject, new Error(m.message || 'PFD 掩模生成失败'))
    })
    worker.on('error', (e) => finish(reject, e))
    worker.on('exit', (code) => { if (!settled) finish(reject, new Error(`PFD 计算线程异常退出（${code}）`)) })
  })
  return { promise, cancel: () => cancelFn() }
}

// ---- worker 入口 ----
if (!isMainThread && parentPort && workerData && workerData.kind === WORKER_KIND) {
  const flag = new Int32Array(workerData.cancel)
  let last = 0
  try {
    const r = generate(workerData.req, {
      shouldCancel: () => Atomics.load(flag, 0) === 1,
      onProgress: (done, total) => {
        const now = Date.now()
        if (done < total && now - last < 100) return     // 节流：约 10 次/秒，末一条照发
        last = now
        parentPort.postMessage({ type: 'progress', done, total })
      }
    })
    const transfer = packBytes(r)
    parentPort.postMessage({ type: 'done', result: r }, transfer)
  } catch (e) {
    parentPort.postMessage(e && e.canceled ? { type: 'canceled' } : { type: 'error', message: (e && e.message) || String(e) })
  }
}

module.exports = { generate, packBytes, slim, start, WORKER_KIND }
